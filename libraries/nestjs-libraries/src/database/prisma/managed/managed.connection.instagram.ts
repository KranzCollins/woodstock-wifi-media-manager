import {
  ManagedConnectionGrant,
  ManagedConnectionProvider,
  ManagedConnectionProviderError,
} from '@gitroom/nestjs-libraries/database/prisma/managed/managed.connection.provider';

// Instagram API with Instagram Login, for managed connections only
// (docs/managed-extension/account-connection.md). The protocol is the one the
// pinned upstream adapter uses (integrations/social/instagram.standalone
// .provider.ts at bd8353f): the same authorize URL parameters, the same three
// calls and the same fields. Meta's current documentation could not be read
// for this change, so nothing here goes beyond that source: no PKCE (upstream
// sends none) and no claim about which scopes Meta grants. Differences from
// upstream, all on our side of the protocol:
// - a 256-bit state generated by the service, not makeSecureId(6)
// - one fixed https redirect URI from its own variable, never redirectmeto.com
// - the requested scopes are an operator-chosen subset of the reviewed list,
//   checked against the first answer before a long-lived token is asked for
// - every call stops on the exchange's AbortSignal, refuses redirects and
//   reads at most MAX_RESPONSE_BYTES
// - the provider's expires_in is recorded, not a 58-day assumption
// - no provider answer, URL or error is logged or put in an error

const AUTHORIZE_URL = 'https://www.instagram.com/oauth/authorize';
const TOKEN_URL = 'https://api.instagram.com/oauth/access_token';
const EXCHANGE_URL = 'https://graph.instagram.com/access_token';
// META_GRAPH_API_VERSION of the pinned facebook.provider.ts, copied so this
// adapter does not load the upstream providers
const GRAPH_VERSION = 'v25.0';
const ME_URL = `https://graph.instagram.com/${GRAPH_VERSION}/me`;

// The scopes the upstream adapter requests, the only ones that were reviewed.
// basic is the one the account identity (/me) needs
export const INSTAGRAM_REVIEWED_SCOPES = [
  'instagram_business_basic',
  'instagram_business_content_publish',
  'instagram_business_manage_comments',
  'instagram_business_manage_insights',
] as const;
export const INSTAGRAM_DEFAULT_SCOPES = ['instagram_business_basic'];

// every answer of these endpoints is a small JSON object
export const MAX_RESPONSE_BYTES = 64 * 1024;
// a sanity bound on the provider's expires_in, not an expectation
const MAX_EXPIRES_IN_SECONDS = 10 * 365 * 24 * 60 * 60;

const APP_ID = /^[A-Za-z0-9]{1,64}$/;
const APP_SECRET = /^[\x21-\x7e]{1,256}$/;
const INTERNAL_ID = /^[A-Za-z0-9_.:-]{1,128}$/;
const PROFILE = /^[^\s\u0000-\u001f\u007f]{1,128}$/;
const MAX_SCOPES = 32;

export type ManagedConnectionFetch = (
  input: string,
  init: RequestInit
) => Promise<Response>;

interface InstagramConfig {
  appId: string;
  appSecret: string;
  redirectUri: string;
  scopes: string[];
}

// The exact URL registered with the Meta app: https, no credentials, query or
// fragment, and written in its canonical form so the authorize request and
// the exchange send the same string
function redirectUri(value: string | undefined) {
  let url: URL;
  try {
    url = new URL(String(value));
  } catch (err) {
    return null;
  }

  if (
    url.protocol !== 'https:' ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.hostname === 'redirectmeto.com' ||
    url.toString() !== value
  ) {
    return null;
  }

  return value;
}

function requestedScopes(value: string | undefined) {
  if (!value) {
    return INSTAGRAM_DEFAULT_SCOPES;
  }

  const scopes = [...new Set(value.split(',').map((scope) => scope.trim()))];
  if (
    !scopes.includes('instagram_business_basic') ||
    !scopes.every((scope) =>
      (INSTAGRAM_REVIEWED_SCOPES as readonly string[]).includes(scope)
    )
  ) {
    return null;
  }

  return scopes;
}

// the formats upstream checkScopes accepts: a list, or one comma or space
// separated (and possibly URL-encoded) string
function grantedScopes(permissions: unknown): string[] {
  let list: unknown[] = [];
  if (Array.isArray(permissions)) {
    list = permissions;
  } else if (typeof permissions === 'string') {
    let decoded = permissions;
    try {
      decoded = decodeURIComponent(permissions);
    } catch (err) {
      return [];
    }
    list = decoded.split(decoded.includes(',') ? ',' : ' ');
  }

  return list
    .filter(
      (scope): scope is string =>
        typeof scope === 'string' && scope.length > 0 && scope.length <= 128
    )
    .map((scope) => scope.trim())
    .slice(0, MAX_SCOPES);
}

async function readBounded(response: Response) {
  const reader = response.body?.getReader();
  if (!reader) {
    return '';
  }

  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) {
      break;
    }

    total += value.byteLength;
    if (total > MAX_RESPONSE_BYTES) {
      await reader.cancel().catch(() => undefined);
      throw new Error('Provider answer too large');
    }
    chunks.push(value);
  }

  return Buffer.concat(chunks).toString('utf8');
}

export class InstagramStandaloneConnectionAdapter
  implements ManagedConnectionProvider
{
  readonly identifier = 'instagram-standalone';

  constructor(
    private _fetch: ManagedConnectionFetch = (input, init) =>
      fetch(input, init),
    private _env: NodeJS.ProcessEnv = process.env
  ) {}

  // read on every call, so the operator's current configuration applies;
  // null when any part of it is missing or invalid
  private config(): InstagramConfig | null {
    const appId = this._env.INSTAGRAM_APP_ID;
    const appSecret = this._env.INSTAGRAM_APP_SECRET;
    const redirect = redirectUri(
      this._env.POSTIZ_MANAGED_INSTAGRAM_REDIRECT_URI
    );
    const scopes = requestedScopes(this._env.POSTIZ_MANAGED_INSTAGRAM_SCOPES);

    if (
      typeof appId !== 'string' ||
      !APP_ID.test(appId) ||
      typeof appSecret !== 'string' ||
      !APP_SECRET.test(appSecret) ||
      !redirect ||
      !scopes
    ) {
      return null;
    }

    return { appId, appSecret, redirectUri: redirect, scopes };
  }

  available() {
    return !!this.config();
  }

  // Instagram reports the username in lowercase, without an @ and without
  // spaces. The expected profile is compared with it as given, so any other
  // spelling would only fail after a token was issued and dropped. Nothing
  // is normalized here: W&W writes the canonical form before it asks
  expectedProfileRefusal(profile: string) {
    return profile.startsWith('@') ||
      /\s/.test(profile) ||
      profile !== profile.toLowerCase()
      ? 'For Instagram, expectedAccount.profile must be the username exactly as Instagram reports it: lowercase, without a leading @ and without spaces'
      : null;
  }

  authorizationUrl(state: string) {
    const config = this.config();
    if (!config) {
      throw new ManagedConnectionProviderError('NOT_SENT');
    }

    // upstream's parameter order and values; the scope list is joined with
    // commas like upstream
    return `${AUTHORIZE_URL}?${new URLSearchParams({
      enable_fb_login: '0',
      client_id: config.appId,
      redirect_uri: config.redirectUri,
      response_type: 'code',
      scope: config.scopes.join(','),
      state,
    }).toString()}`;
  }

  // One request to an exact endpoint. A thrown fetch error is replaced, not
  // wrapped: its message or cause can carry the URL, and with it the secret
  private async call(
    url: string,
    init: RequestInit,
    signal: AbortSignal
  ): Promise<{ status: number; body: any }> {
    let response: Response;
    let text: string;
    try {
      response = await this._fetch(url, {
        ...init,
        signal,
        redirect: 'error',
      });
      text = await readBounded(response);
    } catch (err) {
      throw new Error('Provider call failed');
    }

    let body: any = null;
    try {
      body = JSON.parse(text);
    } catch (err) {
      body = null;
    }

    return {
      status: response.status,
      body: body && typeof body === 'object' && !Array.isArray(body) ? body : null,
    };
  }

  async exchange(
    code: string,
    signal: AbortSignal
  ): Promise<ManagedConnectionGrant> {
    const config = this.config();
    if (!config || signal.aborted) {
      throw new ManagedConnectionProviderError('NOT_SENT');
    }

    // 1. the code for a short-lived token (multipart, like upstream)
    const form = new FormData();
    form.append('client_id', config.appId);
    form.append('client_secret', config.appSecret);
    form.append('grant_type', 'authorization_code');
    form.append('redirect_uri', config.redirectUri);
    form.append('code', code);

    const short = await this.call(
      TOKEN_URL,
      { method: 'POST', body: form },
      signal
    );

    const shortToken = short.body?.access_token;
    if (typeof shortToken !== 'string' || !shortToken) {
      // A 4xx answer that carries an error is the provider refusing the
      // code. Anything else (5xx, no body, a 200 without a token) may have
      // issued a token, so it stays unknown
      const refused =
        short.status >= 400 &&
        short.status < 500 &&
        !!short.body &&
        ['error', 'error_type', 'error_message'].some(
          (field) => field in short.body
        );
      throw refused
        ? new ManagedConnectionProviderError('REFUSED')
        : new Error('Unexpected token answer');
    }

    // upstream checks the same permissions, but only after the long-lived
    // token was issued; here no long-lived token is asked for without them
    const scopes = grantedScopes(short.body.permissions);
    if (!config.scopes.every((scope) => scopes.includes(scope))) {
      throw new ManagedConnectionProviderError('SCOPES_MISSING');
    }

    // 2. the short-lived token for a long-lived one. Upstream's protocol puts
    // the app secret and the token in the query string: this URL is never
    // logged or put in an error
    const long = await this.call(
      `${EXCHANGE_URL}?${new URLSearchParams({
        grant_type: 'ig_exchange_token',
        client_id: config.appId,
        client_secret: config.appSecret,
        access_token: shortToken,
      }).toString()}`,
      { method: 'GET' },
      signal
    );

    const accessToken = long.body?.access_token;
    if (typeof accessToken !== 'string' || !accessToken) {
      throw new Error('Unexpected exchange answer');
    }

    const expiresIn = long.body.expires_in;

    // 3. who authorized. The picture URL upstream also reads is not asked
    // for: nothing here stores or fetches pictures
    const me = await this.call(
      `${ME_URL}?${new URLSearchParams({
        fields: 'user_id,username,name',
        access_token: accessToken,
      }).toString()}`,
      { method: 'GET' },
      signal
    );

    const userId = me.body?.user_id;
    const internalId =
      typeof userId === 'string' || typeof userId === 'number'
        ? String(userId)
        : '';
    if (!INTERNAL_ID.test(internalId)) {
      throw new Error('Unexpected account answer');
    }

    const username = me.body.username;
    const name = me.body.name;

    return {
      account: {
        internalId,
        profile:
          typeof username === 'string' && PROFILE.test(username)
            ? username
            : null,
        displayName:
          typeof name === 'string' && name.trim()
            ? name.trim().slice(0, 256)
            : null,
      },
      credential: {
        accessToken,
        // upstream stores the access token as the refresh token as well
        // (ig_refresh_token refreshes the access token itself)
        refreshToken: accessToken,
        expiresInSeconds:
          Number.isInteger(expiresIn) &&
          expiresIn > 0 &&
          expiresIn <= MAX_EXPIRES_IN_SECONDS
            ? expiresIn
            : null,
      },
      grantedScopes: scopes,
    };
  }
}
